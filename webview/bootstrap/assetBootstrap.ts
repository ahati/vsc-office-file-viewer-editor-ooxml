/**
 * Webview bootstrap: prepares every asset an engine needs before it is mounted.
 *
 * Runs on the webview main thread, inside the entry bundles, *before* the format mount (and before
 * any dynamic `import()` of an engine package, whose module scope resolves asset URLs eagerly).
 * Contract (DESIGN §4.2):
 *
 *   1. read `out/media/manifest.json` via the `mediaBase` webview URI,
 *   2. install the manifest-driven `__boAssetUrl` / `__boWorkerUrl` resolvers — the build rewrote
 *      every engine `new URL('<literal>', import.meta.url)` lookup into a call to these globals
 *      (scripts/build.mjs, `asset-import-rewrite`),
 *   3. fetch every wasm/ttf byte as an `ArrayBuffer` (report S1: the engines have no asset-root
 *      override knobs, so bytes we hand over are the only reliable path),
 *   4. fetch the docx engine worker bundle and turn it into a `blob:` URL (a VS Code webview worker
 *      must never import/fetch a webview resource itself — microsoft/vscode#315494),
 *   5. wrap `self.Worker` so every spawned worker receives the byte map as its very first message
 *      (`{ type: 'bo-assets' }`), which `workerFetchShim.ts` serves from `bo-asset://` URLs.
 *
 * The Webview main thread keeps its own copy of every byte: docx loads its wasm + TTF files on the
 * main thread through `__boAssetUrl(...)` (fetch of a `cspSource` URL, the supported path), while
 * the worker receives *copies* so the main-thread buffers stay usable. The extra copy only happens
 * when an engine actually spawns a worker.
 *
 * M1 tradeoff, deliberately simple: the whole asset set (all wasm modules + the ~15 MB Latin font
 * set) is fetched for the opened format even though a format only needs a subset. TODO(lazy-assets):
 * switch to per-format asset sets (or lazy per-asset fetch-on-demand) once: (a) the docx worker's
 * wasm set is split into parse/layout/edit/opc groups, and (b) fonts are subset per document;
 * `manifest.json` already carries per-asset paths so the change stays local to this module.
 */
import type { ViewerFormat, ViewerWebviewConfig } from '../protocol';

/** `out/media/manifest.json` (generated by scripts/build.mjs). */
export interface AssetManifest {
	/** Original asset basename (e.g. `docx_edit_bg.wasm`, `Carlito-Regular.ttf`) -> out/media path. */
	assets: Record<string, string>;
	/** Logical engine worker name -> out/media path. */
	workers: Record<string, string>;
}

/** Phase names recorded by {@link recordTiming} / reported in the `loaded` message (DESIGN §9). */
export type BootstrapPhase =
	| 'init-received'
	| 'bootstrap-start'
	| 'manifest'
	| 'assets-fetched'
	| 'worker-blob'
	| 'bootstrap-done'
	| 'wasm-ready'
	| 'mounted';

export interface BootstrapOptions {
	/** Format whose worker bundle should be prepared; defaults to the host-provided `__BO_FORMAT__`. */
	format?: ViewerFormat;
}

interface BootstrapState {
	/** In-flight/settled bootstrap promise: makes {@link bootstrap} idempotent. */
	ready?: Promise<void>;
	mediaBase: string;
	manifest?: AssetManifest;
	/** Fetched asset bytes, keyed by manifest asset basename. Never detached (see module doc). */
	assetBytes: Map<string, ArrayBuffer>;
	docxWorkerBlobUrl?: string;
	startedAt: number;
	timings: Record<string, number>;
	/** Promise of `{ type: 'bo-assets' }` payloads pending delivery to a spawn. */
	installed: boolean;
}

const state: BootstrapState = {
	mediaBase: '',
	assetBytes: new Map(),
	startedAt: now(),
	timings: {},
	installed: false,
};

/** `performance.now()` with a safe fallback (workers/webviews always have it, be defensive). */
function now(): number {
	return typeof performance !== 'undefined' && typeof performance.now === 'function' ? performance.now() : Date.now();
}

/** Records the elapsed ms since the previous phase (and since bootstrap start for the first one). */
export function recordTiming(phase: string, at: number = now()): void {
	state.timings[phase] = Math.max(0, Math.round(at - state.startedAt));
}

/** All recorded phase timings in ms, relative to the first recorded event (`init-received`). */
export function getTimings(): Record<string, number> {
	return { ...state.timings };
}

/** Webview URI of `out/media/` (trailing slash). Empty until {@link bootstrap} resolves. */
export function getMediaBase(): string {
	return state.mediaBase;
}

/** Absolute URL of a manifest asset, or `undefined` when the manifest does not list it. */
export function getAssetUrl(name: string, fallbackUrl?: string): string {
	const relPath = state.manifest?.assets[name];
	if (relPath) return state.mediaBase + relPath;
	return fallbackUrl ?? `bo-missing-asset://${encodeURIComponent(name)}`;
}

/** Bytes of a manifest asset fetched during {@link bootstrap} (docx/pptx pass these to `initWasm`). */
export function getAssetBytes(name: string): ArrayBuffer | undefined {
	return state.assetBytes.get(name);
}

/**
 * `blob:` URL of the docx engine worker bundle, awaited during {@link bootstrap} when the format is
 * docx. Throws when the bundle was not prepared (wrong format) so the failure is actionable.
 */
export function getDocxWorkerBlobUrl(): string {
	if (!state.docxWorkerBlobUrl) {
		throw new Error('docx engine worker bundle was not prepared by bootstrap() (format mismatch?)');
	}
	return state.docxWorkerBlobUrl;
}

/**
 * Derives the dangling-slash media base from the host HTML when the caller does not pass one.
 * `src/providers/officeProvider.ts` sets `<base href="${mediaBase}" />`, so `document.baseURI` is
 * the media directory.
 */
function resolveMediaBase(mediaBase?: string): string {
	const candidate = mediaBase ?? (typeof document !== 'undefined' ? document.baseURI : '');
	return candidate.replace(/\/?$/, '/');
}

function detectFormat(): ViewerFormat | undefined {
	const fromHost = (globalThis as { __BO_FORMAT__?: unknown }).__BO_FORMAT__;
	return fromHost === 'docx' || fromHost === 'xlsx' || fromHost === 'pptx' || fromHost === 'vsdx' ? fromHost : undefined;
}

/** Installs the manifest-backed `__boAssetUrl` / `__boWorkerUrl` globals (build-injected lookups). */
function installAssetUrlGlobals(): void {
	globalThis.__boAssetUrl = (name: string, fallbackUrl?: string): string => {
		const relPath = state.manifest?.assets[name];
		if (relPath) return state.mediaBase + relPath;
		// Unknown asset: keep the esbuild-emitted URL (relative to <base>) rather than throwing —
		// a single missing face must not take the whole viewer down.
		return fallbackUrl ?? `bo-missing-asset://${encodeURIComponent(name)}`;
	};
	globalThis.__boWorkerUrl = (logical: string): string => {
		if (logical === 'docx') return getDocxWorkerBlobUrl();
		// xlsx/pptx run in-thread (their dists ship no worker anywhere); anything else is a bug.
		throw new Error(`no engine worker bundle is available for "${logical}" (xlsx/pptx run in-thread)`);
	};
}

/**
 * Spawns are wrapped so the asset map is posted before any engine message. `postMessage` to a
 * dedicated worker preserves order, so `bo-assets` is always the first message the shim sees — even
 * if the engine posts `warm`/`open` in the same task.
 */
function installWorkerAssetHandshake(): void {
	if (state.installed) return;
	state.installed = true;
	if (typeof Worker !== 'function') return;

	const OriginalWorker = Worker;
	// Structural clone of the built-in Worker so `new Worker(...)` (and `instanceof`) keep working.
	class AssetSeededWorker extends OriginalWorker {
		constructor(url: string | URL, options?: WorkerOptions) {
			super(url, options);
			try {
				// Copies, not transfers: transferring detaches the main thread's buffers, which docx
				// still needs for its main-thread wasm modules and font loading.
				const assets: Record<string, ArrayBuffer> = {};
				const transfer: ArrayBuffer[] = [];
				for (const [name, bytes] of state.assetBytes) {
					const copy = bytes.slice(0);
					assets[name] = copy;
					transfer.push(copy);
				}
				this.postMessage({ type: 'bo-assets', assets }, transfer);
			} catch (error) {
				// Never let seeding break worker construction: the shim will serve whatever it got
				// (or report the failing asset through the structured error panel).
				console.warn('[betteroffice-viewer] failed to seed engine worker assets', error);
			}
		}
	}
	(globalThis as { Worker: typeof Worker }).Worker = AssetSeededWorker as unknown as typeof Worker;
}

/** Fetches `manifest.json` and installs the asset resolvers. */
async function loadManifest(mediaBase: string): Promise<AssetManifest> {
	const response = await fetch(`${mediaBase}manifest.json`, { cache: 'no-store' });
	if (!response.ok) throw new Error(`asset manifest fetch failed: HTTP ${response.status} ${response.statusText}`);
	const manifest = (await response.json()) as AssetManifest;
	if (!manifest || typeof manifest !== 'object' || !manifest.assets || typeof manifest.assets !== 'object') {
		throw new Error('asset manifest is malformed: expected { assets: Record<string, string> }');
	}
	manifest.workers = manifest.workers ?? {};
	state.manifest = manifest;
	installAssetUrlGlobals();
	recordTiming('manifest');
	return manifest;
}

/** Bounded-concurrency fetch of every manifest asset into {@link BootstrapState.assetBytes}. */
async function fetchAssets(manifest: AssetManifest, mediaBase: string): Promise<void> {
	const entries = Object.entries(manifest.assets);
	const CONCURRENCY = 6;
	let cursor = 0;

	const worker = async (): Promise<void> => {
		for (;;) {
			const index = cursor++;
			const entry = entries[index];
			if (!entry) return;
			const [name, relPath] = entry;
			const response = await fetch(mediaBase + relPath, { cache: 'force-cache' });
			if (!response.ok) {
				throw new Error(`asset fetch failed for ${name}: HTTP ${response.status} ${response.statusText}`);
			}
			state.assetBytes.set(name, await response.arrayBuffer());
		}
	};

	await Promise.all(Array.from({ length: Math.min(CONCURRENCY, entries.length) }, worker));
	recordTiming('assets-fetched');
}

/** Fetches the docx engine worker bundle and exposes it as a blob URL for `new Worker`. */
async function prepareDocxWorker(manifest: AssetManifest, mediaBase: string): Promise<void> {
	const relPath = manifest.workers.docx;
	if (!relPath) throw new Error('asset manifest does not list a docx engine worker');

	const response = await fetch(mediaBase + relPath, { cache: 'force-cache' });
	if (!response.ok) throw new Error(`docx worker fetch failed: HTTP ${response.status} ${response.statusText}`);
	const source = await response.text();
	state.docxWorkerBlobUrl = URL.createObjectURL(new Blob([source], { type: 'text/javascript' }));
	recordTiming('worker-blob');
}

/**
 * Prepares the asset pipeline for one webview entry. Idempotent: concurrent/duplicate calls share
 * one promise, so a second `init` (reload) resolves immediately.
 *
 * `config.fonts === 'off'` skips nothing here — the bytes are still fetched because docx/pptx
 * engines that run without a bundled-font provider fall back to their own defaults; the font
 * *provider* is what `webview/fonts.ts` gates on that setting.
 */
export async function bootstrap(
	_config: ViewerWebviewConfig,
	mediaBase?: string,
	options: BootstrapOptions = {},
): Promise<void> {
	if (state.ready) return state.ready;

	state.mediaBase = resolveMediaBase(mediaBase);
	state.startedAt = now();
	recordTiming('bootstrap-start');
	const format = options.format ?? detectFormat();

	state.ready = (async () => {
		const manifest = await loadManifest(state.mediaBase);
		await fetchAssets(manifest, state.mediaBase);
		if (format === undefined || format === 'docx') {
			// docx is the only format with an engine worker (xlsx/pptx dists ship none) — and the
			// host reports the format, so other views never pay for this fetch.
			await prepareDocxWorker(manifest, state.mediaBase);
		}
		installWorkerAssetHandshake();
		recordTiming('bootstrap-done');
	})();

	try {
		await state.ready;
	} catch (error) {
		// Allow a retry (a fresh blob/asset fetch is exactly what a transient webview failure needs,
		// DESIGN §4.3); the entry reports the phase+message through the error panel.
		state.ready = undefined;
		throw error;
	}
}

/** Test/debug hook: forgets every fetched byte and URL (not used by the view entries). */
export function resetBootstrapForTests(): void {
	if (state.docxWorkerBlobUrl) URL.revokeObjectURL(state.docxWorkerBlobUrl);
	state.ready = undefined;
	state.manifest = undefined;
	state.docxWorkerBlobUrl = undefined;
	state.assetBytes.clear();
	state.timings = {};
	state.mediaBase = '';
	state.installed = false;
}

